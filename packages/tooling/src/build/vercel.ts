import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

import { type AppEntry } from "../entry-points.ts";
import { type BuildTargetAdapter } from "./types.ts";

/**
 * Vercel ships only what it can trace through imports, so assets travel inside
 * the server bundle. Base64 keeps binaries intact.
 */
const readClientAssets = async (dir: string) =>
  Object.fromEntries(
    await Promise.all(
      (await readdir(dir)).map(
        async (file) =>
          [file, (await readFile(join(dir, file))).toString("base64")] as const,
      ),
    ),
  );

/**
 * Vercel's Hono preset serves this file, and its imports are what the deploy
 * traces — an app missing here silently does not deploy. They are awaited one
 * at a time because an app fixes its `BASE_PATH` when it evaluates.
 */
const writeVercelEntry = async ({
  rootDir,
  server,
}: {
  rootDir: string;
  server: AppEntry[];
}) => {
  const mounts = server.flatMap(({ name }, index) => [
    // A lone app keeps whatever prefix the deployment configured.
    ...(server.length > 1
      ? [`process.env.BASE_PATH = ${JSON.stringify(`/${name}`)};`]
      : []),
    `const { app: app${index} } = await import("./dist/${name}/entry-server.js");`,
    `server.route("/", app${index});`,
    "",
  ]);

  await writeFile(
    join(rootDir, "index.js"),
    [
      "// Generated by @nimara/tooling buildApps. Do not edit.",
      'import { Hono } from "hono";',
      "",
      "const server = new Hono();",
      "",
      ...mounts,
      "// eslint-disable-next-line import/no-default-export",
      "export default server;",
      "",
    ].join("\n"),
  );
};

export const vercelTarget: BuildTargetAdapter = {
  clientAssets: async ({ assetsDir, hasClient }) =>
    hasClient ? readClientAssets(assetsDir) : {},

  finalize: writeVercelEntry,
};
